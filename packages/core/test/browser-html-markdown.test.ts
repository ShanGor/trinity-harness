import { describe, expect, it } from 'vitest';
import { browserHtmlToMarkdown } from '../src/tools/browser-html-markdown.js';

describe('offline Turndown conversion', () => {
  it('preserves Unicode, ordered starts, nested lists, fenced code, links and local images', async () => {
    const result = await browserHtmlToMarkdown(
      '<h2>中文 😀</h2><ol start="3"><li>Third<ul><li>Nested</li></ul></li></ol><pre><code>const x = 1;\n</code></pre><p><a href="https://example.com/source">Source</a><img src="media/abc.png" alt="Figure"></p>',
    );
    expect(result.text).toContain('## 中文 😀');
    expect(result.text).toMatch(/3\.\s+Third/);
    expect(result.text).toMatch(/\s+-\s+Nested/);
    expect(result.text).toContain('```\nconst x = 1;');
    expect(result.text).toContain('[Source](https://example.com/source)');
    expect(result.text).toContain('![Figure](media/abc.png)');
    expect(result.warnings).toBe(false);
  });

  it('retains graphical SVG without text even inside otherwise blank containers', async () => {
    const html =
      '<div><span><svg viewBox="0 0 8 24"><path d="M4 0V20" stroke="currentColor"></path></svg></span></div>';
    const result = await browserHtmlToMarkdown(html);
    expect(result.text).toContain('<svg');
    expect(result.text).toContain('M4 0V20');
    expect(result.warnings).toBe(true);
    expect(result.warningCodes).toEqual(['inline-svg']);
  });

  it('uses GFM tables and preserves unsupported tables as HTML with a warning', async () => {
    const simple = await browserHtmlToMarkdown(
      '<table><tr><th>Name</th><th>Value</th></tr><tr><td>A</td><td>B</td></tr></table>',
    );
    expect(simple.text).toContain('| Name | Value |');
    expect(simple.text).toMatch(/\| --- \| --- \|/);
    expect(simple.warnings).toBe(false);
    for (const html of [
      '<table><tr><td>Without heading</td></tr></table>',
      '<table><tr><th colspan="2">Merged</th></tr><tr><td>A</td><td>B</td></tr></table>',
    ]) {
      const result = await browserHtmlToMarkdown(html);
      expect(result.text.replace(/<\/?tbody>/g, '')).toContain(html);
      expect(result.warnings).toBe(true);
      expect(result.warningCodes).toEqual(['unsupported-table']);
    }
  });

  it('rejects oversized Markdown generated by escaping smaller HTML input', async () => {
    await expect(
      browserHtmlToMarkdown('<p>' + '\\'.repeat(4 * 1024 * 1024 + 1) + '</p>'),
    ).rejects.toMatchObject({ code: 'LIMIT_REACHED' });
  }, 15000);

  it('does not inherit parent module-mode CLI flags into the CommonJS converter worker', async () => {
    const original = process.execArgv;
    process.execArgv = [...original, '--input-type=module'];
    try {
      expect((await browserHtmlToMarkdown('<h1>CLI conversion</h1>')).text).toContain(
        '# CLI conversion',
      );
    } finally {
      process.execArgv = original;
    }
  });

  it('bounds input and terminates an in-flight conversion on cancellation', async () => {
    await expect(browserHtmlToMarkdown('x'.repeat(16 * 1024 * 1024 + 1))).rejects.toMatchObject({
      code: 'LIMIT_REACHED',
    });
    const controller = new AbortController();
    const result = browserHtmlToMarkdown('<p>text</p>'.repeat(10000), controller.signal);
    controller.abort();
    await expect(result).rejects.toMatchObject({ code: 'CANCELLED' });
  });
});

it('retains CSS grid cells as inert HTML rather than concatenating block spans', async () => {
  const html =
    '<h2>Service status</h2><div style="display:grid;grid-template-columns:100px 200px"><span style="display:block">Service</span><span style="display:block">State</span><span style="display:block">Search</span><span style="display:block">Available</span></div><p>After the grid.</p>';
  const result = await browserHtmlToMarkdown(html);
  expect(result.text).toContain('## Service status');
  expect(result.text).toContain('<div style="display:grid;grid-template-columns:100px 200px">');
  expect(result.text).toContain('<span style="display:block">Service</span>');
  expect(result.text).not.toContain('ServiceStateSearchAvailable');
  expect(result.text).toContain('After the grid.');
  expect(result.warningCodes).toEqual(['layout-html']);
  const inline = await browserHtmlToMarkdown('<p><span>un</span><span>broken</span> word</p>');
  expect(inline.text).toBe('unbroken word\n');
  expect(inline.warningCodes).toEqual([]);
});
