const MEDIA_MIME_TYPES = ['image/png', 'image/jpeg', 'image/webp', 'image/gif', 'application/pdf'];

/** Browser file types are often empty or octet-stream for source/config files. */
export function attachmentMimeType(mimeType: string, filename = ''): string | undefined {
  const mime = mimeType.split(';', 1)[0]!.trim().toLowerCase();
  if (MEDIA_MIME_TYPES.includes(mime)) return mime;
  if (mime.startsWith('text/') || TEXT_MIME_TYPES.includes(mime)) return 'text/plain';
  const name = filename.toLowerCase();
  const extension = name.split('.').at(-1) ?? '';
  return TEXT_EXTENSIONS.includes(extension) || TEXT_FILENAMES.includes(name)
    ? 'text/plain'
    : undefined;
}

/** Native picker hints; upload validation also handles extensionless source files. */
export const ATTACHMENT_ACCEPT = [
  ...MEDIA_MIME_TYPES,
  'text/*',
  ...TEXT_MIME_TYPES,
  ...TEXT_EXTENSIONS.map((extension) => `.${extension}`),
  ...TEXT_FILENAMES.filter((name) => name.startsWith('.')),
].join(',');
